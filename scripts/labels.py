def english(name: str) -> str:
    """A readable English name from the register's identifier."""
    parts = []
    for token in name.split("_"):
        if token in EN_TOKENS:
            parts.append(EN_TOKENS[token])
            continue
        token = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", " ", token)
        token = re.sub(r"(?<=[A-Za-z])(?=\d)", " ", token)
        parts.append(token)
    text = " ".join(p for p in parts if p).strip()
    text = re.sub(r"Fan 1\b", "Fan 1 (supply)", text)
    text = re.sub(r"Fan 2\b", "Fan 2 (exhaust)", text)
    return text[:1].upper() + text[1:]


def russian(name: str) -> str | None:
    """The Russian name of a register, None when no rule knows it."""
    for pattern, render in RULES:
        match = pattern.match(name)
        if match:
            return render(match)
    return None
